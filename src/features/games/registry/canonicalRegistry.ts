function getDistrictForStation(num: number): GameDistrict {
  if (num <= 10) return "money";
  if (num <= 20) return "builders";
  if (num <= 25) return "risk";
  if (num <= 30) return "operations";
  if (num <= 35) return "innovation";
  if (num <= 40) return "leadership";
  if (num <= 45) return "strategy";
  return "launch";
}

function getRequiredTierForStation(num: number): "intern" | "founder" | "tycoon" {
  if (num <= 10) return "intern"; // Free
  if (num <= 35) return "founder";
  return "tycoon";
}

